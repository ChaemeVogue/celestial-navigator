// Generates deterministic placeholder sky images for every mock pass:
//   public/mock/images/<targetId>/pass-<n>.svg  (1200×1200, square like the real cutouts)
// The star field is seeded per target so it is identical across that target's
// passes; only the amber candidate dot moves, matching passes/<id>.json.
//
// Run with: npm run mocks

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

type Pass = { id: string; imageUrl: string }
type Candidate = { positions: { passId: string; x: number; y: number }[] }
type PassesFile = { targetId: string; passes: Pass[]; candidates: Candidate[] }
type ColourKeyEntry = { colour: string }
type Target = { id: string }

const W = 1200
const H = 1200
const SKY_INNER = '#13213D'
const SKY_OUTER = '#060A14'
const AMBER = '#FFB000'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const mockDir = join(root, 'src/api/mock')
const readJson = <T>(path: string): T => JSON.parse(readFileSync(path, 'utf8')) as T

const targets = readJson<Target[]>(join(mockDir, 'targets.json'))
const colours = readJson<ColourKeyEntry[]>(join(mockDir, 'colourKey.json')).map((c) => c.colour)

function seededRandom(text: string) {
  let seed = 0
  for (const ch of text) seed = (seed * 31 + ch.charCodeAt(0)) % 2147483647
  seed = seed || 1
  return () => {
    seed = (seed * 16807) % 2147483647
    return seed / 2147483647
  }
}

const f = (n: number) => n.toFixed(1)

// The target's glow, shaped by kind.
function targetShape(id: string, rand: () => number): string {
  const cx = W / 2
  const cy = H / 2
  switch (id) {
    case 'm31': // long tilted ellipse
      return `<ellipse cx="${cx}" cy="${cy}" rx="460" ry="120" fill="url(#glow-cool)" transform="rotate(-35 ${cx} ${cy})"/>
  <ellipse cx="${cx}" cy="${cy}" rx="140" ry="45" fill="url(#glow-core)" transform="rotate(-35 ${cx} ${cy})"/>`
    case 'm104': // thin, edge-on, with a dust lane
      return `<ellipse cx="${cx}" cy="${cy}" rx="380" ry="80" fill="url(#glow-cool)"/>
  <ellipse cx="${cx}" cy="${cy}" rx="150" ry="55" fill="url(#glow-core)"/>
  <ellipse cx="${cx}" cy="${cy + 6}" rx="330" ry="9" fill="${SKY_OUTER}" opacity="0.75"/>`
    case 'm42': // large diffuse reddish cloud
      return `<ellipse cx="${cx - 40}" cy="${cy + 20}" rx="420" ry="330" fill="url(#glow-warm)" transform="rotate(20 ${cx} ${cy})"/>
  <ellipse cx="${cx + 90}" cy="${cy - 60}" rx="230" ry="170" fill="url(#glow-warm)" opacity="0.7"/>
  <ellipse cx="${cx}" cy="${cy}" rx="90" ry="70" fill="url(#glow-core)"/>`
    case 'm45': {
      // 7 bright blue-white stars with faint haze
      const stars = [
        [-180, -90],
        [-60, -150],
        [40, -60],
        [160, -120],
        [-120, 70],
        [90, 100],
        [230, 40],
      ]
      const haze = `<ellipse cx="${cx}" cy="${cy}" rx="380" ry="260" fill="url(#glow-cool)" opacity="0.6"/>`
      const bright = stars
        .map(([dx, dy]) => {
          const r = 7 + rand() * 4
          const x = cx + dx
          const y = cy + dy
          return `<circle cx="${x}" cy="${y}" r="${f(r * 5)}" fill="url(#glow-star)"/>
  <circle cx="${x}" cy="${y}" r="${f(r)}" fill="#EAF2FF"/>`
        })
        .join('\n  ')
      return `${haze}\n  ${bright}`
    }
    case 'm51': // roughly round, with a small companion
      return `<circle cx="${cx - 30}" cy="${cy + 10}" r="230" fill="url(#glow-cool)"/>
  <circle cx="${cx - 30}" cy="${cy + 10}" r="60" fill="url(#glow-core)"/>
  <circle cx="${cx + 190}" cy="${cy - 170}" r="90" fill="url(#glow-cool)"/>
  <circle cx="${cx + 190}" cy="${cy - 170}" r="25" fill="url(#glow-core)"/>`
    default: // m101 and anything else: roughly round
      return `<ellipse cx="${cx}" cy="${cy}" rx="270" ry="250" fill="url(#glow-cool)"/>
  <circle cx="${cx}" cy="${cy}" r="70" fill="url(#glow-core)"/>`
  }
}

function renderSvg(targetId: string, x: number, y: number): string {
  // Same seed for every pass of a target, so the field never changes.
  const rand = seededRandom(targetId)
  const stars = Array.from({ length: 150 }, () => {
    const cx = rand() * W
    const cy = rand() * H
    const r = 0.6 + rand() * 1.8
    const fill = colours[Math.floor(rand() * colours.length)]
    const opacity = 0.45 + rand() * 0.55
    return `<circle cx="${f(cx)}" cy="${f(cy)}" r="${f(r)}" fill="${fill}" opacity="${opacity.toFixed(2)}"/>`
  }).join('\n  ')
  const shape = targetShape(targetId, rand)
  const dx = (x / 100) * W
  const dy = (y / 100) * H

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- MOCK DATA: placeholder image generated by scripts/generate-mock-images.ts -->
  <defs>
    <radialGradient id="sky" cx="50%" cy="50%" r="70%">
      <stop offset="0%" stop-color="${SKY_INNER}"/>
      <stop offset="100%" stop-color="${SKY_OUTER}"/>
    </radialGradient>
    <radialGradient id="glow-cool">
      <stop offset="0%" stop-color="#9CC3FF" stop-opacity="0.45"/>
      <stop offset="45%" stop-color="#5AA0FF" stop-opacity="0.16"/>
      <stop offset="100%" stop-color="#5AA0FF" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="glow-warm">
      <stop offset="0%" stop-color="#FF8A6B" stop-opacity="0.42"/>
      <stop offset="50%" stop-color="#C2475B" stop-opacity="0.16"/>
      <stop offset="100%" stop-color="#C2475B" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="glow-core">
      <stop offset="0%" stop-color="#F4EFE2" stop-opacity="0.95"/>
      <stop offset="100%" stop-color="#F4EFE2" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="glow-star">
      <stop offset="0%" stop-color="#CFE0FF" stop-opacity="0.5"/>
      <stop offset="100%" stop-color="#CFE0FF" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="glow-amber">
      <stop offset="0%" stop-color="${AMBER}" stop-opacity="0.6"/>
      <stop offset="100%" stop-color="${AMBER}" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#sky)"/>
  ${shape}
  ${stars}
  <circle cx="${f(dx)}" cy="${f(dy)}" r="14" fill="url(#glow-amber)"/>
  <circle cx="${f(dx)}" cy="${f(dy)}" r="4.5" fill="${AMBER}"/>
</svg>
`
}

let count = 0
for (const { id } of targets) {
  const data = readJson<PassesFile>(join(mockDir, 'passes', `${id}.json`))
  const candidate = data.candidates[0]
  const outDir = join(root, 'public/mock/images', id)
  mkdirSync(outDir, { recursive: true })

  data.passes.forEach((pass, i) => {
    // Passes that point at real images (e.g. m101's SPHEREx PNGs) are left alone.
    if (!pass.imageUrl.endsWith('.svg')) return
    const pos = candidate?.positions.find((p) => p.passId === pass.id)
    if (!pos) throw new Error(`${pass.id}: candidate has no position for this pass`)
    writeFileSync(join(outDir, `pass-${i + 1}.svg`), renderSvg(id, pos.x, pos.y))
    count++
  })
}

console.log(`Wrote ${count} mock images to public/mock/images/`)
